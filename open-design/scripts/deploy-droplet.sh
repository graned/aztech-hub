#!/usr/bin/env bash

set -euo pipefail

usage() {
    cat <<'EOF'
Usage: scripts/deploy-droplet.sh [options] <user@host> [remote-directory]

Installs Docker Engine and Docker Compose on an Ubuntu/Debian Droplet,
uploads the production deployment bundle over SSH, and starts the stack.

Arguments:
  user@host          SSH destination, for example root@203.0.113.10
  remote-directory   Installation directory (default: /opt/aztech-open-design)

Environment:
  SSH_PORT            Optional SSH port (default: 22)
  SSH_KEY             Optional path to a private SSH identity file

Options:
  -i, --ssh-key PATH  Private SSH identity file
  -p, --ssh-port PORT SSH port (default: 22)
  -h, --help          Show this help

Before running, create .env.prod from .env.prod.example and fill every
required value. Git is not needed on the Droplet.
EOF
}

fail() {
    printf 'ERROR: %s\n' "$1" >&2
    exit 1
}

ssh_port=${SSH_PORT:-22}
ssh_key=${SSH_KEY:-}
positional=()

while [[ $# -gt 0 ]]; do
    case $1 in
        -i|--ssh-key)
            [[ $# -ge 2 ]] || fail "$1 requires a path"
            ssh_key=$2
            shift 2
            ;;
        --ssh-key=*)
            ssh_key=${1#*=}
            shift
            ;;
        -p|--ssh-port)
            [[ $# -ge 2 ]] || fail "$1 requires a port"
            ssh_port=$2
            shift 2
            ;;
        --ssh-port=*)
            ssh_port=${1#*=}
            shift
            ;;
        -h|--help)
            usage
            exit 0
            ;;
        --)
            shift
            positional+=("$@")
            break
            ;;
        -* )
            fail "unknown option: $1"
            ;;
        *)
            positional+=("$1")
            shift
            ;;
    esac
done

set -- "${positional[@]}"
[[ $# -ge 1 && $# -le 2 ]] || {
    usage >&2
    exit 2
}

target=$1
remote_dir=${2:-/opt/aztech-open-design}

if [[ $ssh_key == '~/'* ]]; then
    ssh_key=$HOME/${ssh_key#\~/}
fi

[[ $target =~ ^[A-Za-z0-9._-]+@[A-Za-z0-9][A-Za-z0-9._:-]*$ ]] \
    || fail "SSH destination must use the form user@host and contain no shell syntax"
[[ $remote_dir =~ ^/opt/[A-Za-z0-9][A-Za-z0-9._-]*$ ]] \
    || fail "remote directory must be a dedicated /opt/<name> path"
[[ $ssh_port =~ ^[1-9][0-9]{0,4}$ && $ssh_port -le 65535 ]] || fail "SSH_PORT must be between 1 and 65535"
if [[ -n $ssh_key ]]; then
    [[ -f $ssh_key ]] || fail "SSH_KEY must point to a readable private key file"
fi

script_dir=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)
project_dir=$(cd -- "$script_dir/.." && pwd)

command -v ssh >/dev/null 2>&1 || fail "ssh is required on the local machine"
command -v tar >/dev/null 2>&1 || fail "tar is required on the local machine"
[[ -f $project_dir/.env.prod && ! -L $project_dir/.env.prod ]] \
    || fail "missing regular .env.prod; copy .env.prod.example and fill it first"

trim_whitespace() {
    local value=$1
    value=${value#"${value%%[![:space:]]*}"}
    value=${value%"${value##*[![:space:]]}"}
    printf '%s' "$value"
}

read_required_env() {
    local requested=$1 line key value found=0
    while IFS= read -r line || [[ -n $line ]]; do
        [[ -z $line || $line == \#* ]] && continue
        [[ $line == *=* ]] || fail "invalid .env.prod line; expected KEY=value"
        key=${line%%=*}
        value=${line#*=}
        if [[ $key == "$requested" ]]; then
            (( found += 1 ))
            [[ $found -eq 1 ]] || fail "$requested is duplicated in .env.prod"
            value=$(trim_whitespace "$value")
            if [[ $value == \'*\' && ${#value} -ge 2 ]]; then
                value=${value:1:${#value}-2}
            elif [[ $value == \"*\" && ${#value} -ge 2 ]]; then
                value=${value:1:${#value}-2}
            fi
            printf '%s' "$value"
        fi
    done < "$project_dir/.env.prod"
    [[ $found -eq 1 ]] || fail "$requested must be set exactly once in .env.prod"
}

design_domain=$(read_required_env DESIGN_DOMAIN)
basic_auth_user=$(read_required_env BASIC_AUTH_USER)
basic_auth_hash=$(read_required_env BASIC_AUTH_HASH)
session_token=$(read_required_env SESSION_TOKEN)

[[ $design_domain =~ ^([A-Za-z0-9]([A-Za-z0-9-]{0,61}[A-Za-z0-9])?\.)+[A-Za-z0-9]([A-Za-z0-9-]{0,61}[A-Za-z0-9])?$ ]] \
    || fail "DESIGN_DOMAIN must be a DNS hostname without a scheme, port, or path"
[[ $basic_auth_user =~ ^[A-Za-z0-9._@-]{1,64}$ ]] \
    || fail "BASIC_AUTH_USER may contain only letters, numbers, dot, underscore, @, and hyphen"
[[ $basic_auth_hash =~ ^\$2[aby]\$[0-9]{2}\$[./A-Za-z0-9]{53}$ ]] \
    || fail "BASIC_AUTH_HASH must be a bcrypt hash generated by caddy hash-password"
[[ $session_token =~ ^[A-Fa-f0-9]{64}$ ]] \
    || fail "SESSION_TOKEN must contain exactly 64 hexadecimal characters"

deploy_files=(
    .dockerignore
    .env.prod
    Caddyfile.prod
    Dockerfile.opendesign
    docker-compose.prod.yml
    scripts/configure-open-design.mjs
)

for file in "${deploy_files[@]}"; do
    [[ -f $project_dir/$file && ! -L $project_dir/$file ]] \
        || fail "required deployment input must be a regular non-symlink file: $file"
done

ssh_args=(
    -p "$ssh_port"
    -o ConnectTimeout=15
    -o StrictHostKeyChecking=yes
)
if [[ -n $ssh_key ]]; then
    ssh_args+=(
        -i "$ssh_key"
        -o IdentitiesOnly=yes
    )
fi

printf 'Bootstrapping Docker on %s...\n' "$target"
ssh "${ssh_args[@]}" "$target" bash -s <<'REMOTE_BOOTSTRAP'
set -euo pipefail

if [[ $(id -u) -eq 0 ]]; then
    sudo_cmd=()
elif command -v sudo >/dev/null 2>&1 && sudo -n true >/dev/null 2>&1; then
    sudo_cmd=(sudo)
else
    printf 'ERROR: remote user must be root or have passwordless sudo (sudo -n)\n' >&2
    exit 1
fi

if [[ $(uname -m) != "x86_64" ]]; then
    printf 'ERROR: this deployment image is currently verified only on x86_64 Droplets\n' >&2
    exit 1
fi

if command -v docker >/dev/null 2>&1; then
    if command -v systemctl >/dev/null 2>&1; then
        "${sudo_cmd[@]}" systemctl enable --now docker
    else
        "${sudo_cmd[@]}" service docker start
    fi
    if "${sudo_cmd[@]}" docker info >/dev/null 2>&1 \
        && "${sudo_cmd[@]}" docker compose version >/dev/null 2>&1 \
        && "${sudo_cmd[@]}" docker buildx version >/dev/null 2>&1; then
        exit 0
    fi
fi

[[ -r /etc/os-release ]] || {
    printf 'ERROR: /etc/os-release is unavailable\n' >&2
    exit 1
}

. /etc/os-release
case ${ID:-} in
    ubuntu|debian) ;;
    *)
        printf 'ERROR: supported remote operating systems are Ubuntu and Debian, found: %s\n' "${ID:-unknown}" >&2
        exit 1
        ;;
esac

codename=${UBUNTU_CODENAME:-${VERSION_CODENAME:-}}
[[ -n $codename ]] || {
    printf 'ERROR: could not determine the apt distribution codename\n' >&2
    exit 1
}

"${sudo_cmd[@]}" apt-get update
"${sudo_cmd[@]}" apt-get install -y ca-certificates curl gnupg
"${sudo_cmd[@]}" install -m 0755 -d /etc/apt/keyrings
"${sudo_cmd[@]}" curl -fsSL "https://download.docker.com/linux/$ID/gpg" -o /etc/apt/keyrings/docker.asc
"${sudo_cmd[@]}" chmod a+r /etc/apt/keyrings/docker.asc
docker_key_fingerprint=
while IFS=: read -r record _ _ _ _ _ _ _ _ value _; do
    if [[ $record == "fpr" ]]; then
        docker_key_fingerprint=$value
        break
    fi
done < <(gpg --batch --show-keys --with-colons /etc/apt/keyrings/docker.asc)
[[ $docker_key_fingerprint == "9DC858229FC7DD38854AE2D88D81803C0EBFCD88" ]] || {
    printf 'ERROR: Docker apt signing-key fingerprint did not match the official key\n' >&2
    exit 1
}

architecture=$(dpkg --print-architecture)
"${sudo_cmd[@]}" tee /etc/apt/sources.list.d/docker.sources >/dev/null <<EOF
Types: deb
URIs: https://download.docker.com/linux/$ID
Suites: $codename
Components: stable
Architectures: $architecture
Signed-By: /etc/apt/keyrings/docker.asc
EOF

"${sudo_cmd[@]}" apt-get update
for conflicting_package in docker.io docker-compose docker-compose-v2 podman-docker containerd runc; do
    "${sudo_cmd[@]}" apt-get remove -y "$conflicting_package" >/dev/null 2>&1 || true
done
"${sudo_cmd[@]}" apt-get install -y docker-ce docker-ce-cli containerd.io docker-buildx-plugin docker-compose-plugin

if command -v systemctl >/dev/null 2>&1; then
    "${sudo_cmd[@]}" systemctl enable --now docker
else
    "${sudo_cmd[@]}" service docker start
fi

"${sudo_cmd[@]}" docker version >/dev/null
"${sudo_cmd[@]}" docker info >/dev/null
"${sudo_cmd[@]}" docker compose version >/dev/null
"${sudo_cmd[@]}" docker buildx version >/dev/null
REMOTE_BOOTSTRAP

printf 'Uploading production files to %s:%s...\n' "$target" "$remote_dir"
remote_archive=$(tar -C "$project_dir" -czf - "${deploy_files[@]}" | \
    ssh "${ssh_args[@]}" "$target" \
        'set -eu; umask 077; archive=$(mktemp /tmp/aztech-open-design.XXXXXX.tar.gz); cat > "$archive"; printf "%s" "$archive"')
[[ $remote_archive =~ ^/tmp/aztech-open-design\.[A-Za-z0-9]+\.tar\.gz$ ]] \
    || fail "remote host returned an invalid temporary archive path"

printf 'Validating and starting Open Design...\n'
ssh "${ssh_args[@]}" "$target" bash -s -- "$remote_dir" "$remote_archive" <<'REMOTE_DEPLOY'
set -euo pipefail
remote_dir=$1
remote_archive=$2

if [[ $(id -u) -eq 0 ]]; then
    sudo_cmd=()
else
    sudo -n true >/dev/null 2>&1 || {
        printf 'ERROR: passwordless sudo is required\n' >&2
        exit 1
    }
    sudo_cmd=(sudo)
fi

[[ $remote_dir =~ ^/opt/[A-Za-z0-9][A-Za-z0-9._-]*$ ]] \
    || { printf 'ERROR: unsafe remote directory\n' >&2; exit 1; }
[[ $remote_archive =~ ^/tmp/aztech-open-design\.[A-Za-z0-9]+\.tar\.gz$ ]] \
    || { printf 'ERROR: unsafe archive path\n' >&2; exit 1; }
[[ ! -L /opt ]] || { printf 'ERROR: /opt must not be a symlink\n' >&2; exit 1; }
[[ ! -L $remote_dir ]] || { printf 'ERROR: remote directory must not be a symlink\n' >&2; exit 1; }
[[ ! -L $remote_dir/scripts ]] || { printf 'ERROR: remote scripts directory must not be a symlink\n' >&2; exit 1; }

staging=$("${sudo_cmd[@]}" mktemp -d /tmp/aztech-open-design-stage.XXXXXX)
cleanup() {
    "${sudo_cmd[@]}" rm -rf "$staging" "$remote_archive"
}
trap cleanup EXIT

"${sudo_cmd[@]}" chmod 0700 "$staging"
expected_members=$'.dockerignore\n.env.prod\nCaddyfile.prod\nDockerfile.opendesign\ndocker-compose.prod.yml\nscripts/configure-open-design.mjs'
archive_members=$("${sudo_cmd[@]}" tar -tzf "$remote_archive")
[[ $archive_members == "$expected_members" ]] \
    || { printf 'ERROR: deployment archive contains unexpected members\n' >&2; exit 1; }
"${sudo_cmd[@]}" tar --no-same-owner --no-same-permissions -xzf "$remote_archive" -C "$staging"

required_files=(
    .dockerignore
    .env.prod
    Caddyfile.prod
    Dockerfile.opendesign
    docker-compose.prod.yml
    scripts/configure-open-design.mjs
)
for file in "${required_files[@]}"; do
    "${sudo_cmd[@]}" test -f "$staging/$file" \
        && "${sudo_cmd[@]}" test ! -L "$staging/$file" \
        || { printf 'ERROR: invalid deployment archive member: %s\n' "$file" >&2; exit 1; }
done

"${sudo_cmd[@]}" install -d -o root -g root -m 0755 "$remote_dir" "$remote_dir/scripts"
"${sudo_cmd[@]}" install -o root -g root -m 0600 "$staging/.env.prod" "$remote_dir/.env.prod.new"
"${sudo_cmd[@]}" install -o root -g root -m 0644 "$staging/.dockerignore" "$remote_dir/.dockerignore"
"${sudo_cmd[@]}" install -o root -g root -m 0644 "$staging/Caddyfile.prod" "$remote_dir/Caddyfile.prod"
"${sudo_cmd[@]}" install -o root -g root -m 0644 "$staging/Dockerfile.opendesign" "$remote_dir/Dockerfile.opendesign"
"${sudo_cmd[@]}" install -o root -g root -m 0644 "$staging/docker-compose.prod.yml" "$remote_dir/docker-compose.prod.yml"
"${sudo_cmd[@]}" install -o root -g root -m 0644 "$staging/scripts/configure-open-design.mjs" "$remote_dir/scripts/configure-open-design.mjs"
"${sudo_cmd[@]}" mv -f "$remote_dir/.env.prod.new" "$remote_dir/.env.prod"

compose=(
    "${sudo_cmd[@]}" docker compose
    --project-directory "$remote_dir"
    --env-file "$remote_dir/.env.prod"
    -f "$remote_dir/docker-compose.prod.yml"
)

diagnostics() {
    local status=$?
    trap - ERR
    "${compose[@]}" ps -a >&2 || true
    "${compose[@]}" logs --no-color --tail=100 configure-open-design open-design caddy >&2 || true
    exit "$status"
}
trap diagnostics ERR

"${compose[@]}" config --quiet
"${compose[@]}" run --rm --no-deps caddy caddy validate \
    --config /etc/caddy/Caddyfile --adapter caddyfile
"${compose[@]}" up -d --build --remove-orphans

deadline=$((SECONDS + 180))
while (( SECONDS < deadline )); do
    container_id=$("${compose[@]}" ps -q open-design)
    if [[ -n $container_id ]]; then
        health=$("${sudo_cmd[@]}" docker inspect \
            --format '{{if .State.Health}}{{.State.Health.Status}}{{else}}missing{{end}}' \
            "$container_id")
        if [[ $health == "healthy" ]]; then
            initializer_id=$("${compose[@]}" ps -a -q configure-open-design)
            initializer_result=$("${sudo_cmd[@]}" docker inspect \
                --format '{{.State.Status}}:{{.State.ExitCode}}' "$initializer_id")
            [[ $initializer_result == "exited:0" ]] || {
                printf 'ERROR: Open Design initializer did not complete successfully\n' >&2
                exit 1
            }
            caddy_id=$("${compose[@]}" ps -q caddy)
            caddy_running=$("${sudo_cmd[@]}" docker inspect --format '{{.State.Running}}' "$caddy_id")
            [[ $caddy_running == "true" ]] || {
                printf 'ERROR: Caddy is not running\n' >&2
                exit 1
            }
            trap - ERR
            "${compose[@]}" ps
            exit 0
        fi
        if [[ $health == "unhealthy" ]]; then
            "${compose[@]}" logs --no-color --tail=100 configure-open-design open-design caddy >&2
            printf 'ERROR: Open Design became unhealthy\n' >&2
            exit 1
        fi
    fi
    sleep 3
done

"${compose[@]}" logs --no-color --tail=100 configure-open-design open-design caddy >&2
printf 'ERROR: Open Design did not become healthy within 180 seconds\n' >&2
exit 1
REMOTE_DEPLOY

printf '\nDeployment completed. Verify https://%s after DNS reaches the Droplet.\n' "$design_domain"
