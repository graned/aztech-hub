#!/usr/bin/env bash
set -Eeuo pipefail

readonly ssh_root="${OPENCODE_SSH_DIR:-${HOME}/.config/opencode-workspace-manager/ssh}"
readonly key_path="${OPENCODE_SSH_KEY_PATH:-${ssh_root}/id_ed25519}"
readonly known_hosts_path="${OPENCODE_KNOWN_HOSTS_PATH:-${ssh_root}/known_hosts}"
readonly env_path="${OPENCODE_SSH_ENV_FILE:-.env.ssh}"

die() {
  printf 'error: %s\n' "$1" >&2
  exit 1
}

if ! command -v gh >/dev/null 2>&1; then
  die "GitHub CLI is required. Install gh, then rerun this script."
fi

if ! gh auth status --hostname github.com >/dev/null 2>&1; then
  printf '%s\n' \
    'GitHub CLI is not authenticated. Authenticate with your GitHub account, then rerun:' \
    '  gh auth login --web --hostname github.com' >&2
  exit 2
fi

github_login="$(gh api user --jq '.login')"
[[ -n "${github_login}" ]] || die "GitHub CLI returned no authenticated username."

mkdir -p "${ssh_root}"
chmod 700 "${ssh_root}"

if [[ ! -f "${key_path}" ]]; then
  printf 'Generating dedicated SSH key for GitHub account %s...\n' "${github_login}"
  ssh-keygen -t ed25519 \
    -f "${key_path}" \
    -N '' \
    -C "opencode-workspace-manager@${github_login}" \
    >/dev/null
  chmod 600 "${key_path}"
  chmod 644 "${key_path}.pub"
else
  [[ -f "${key_path}.pub" ]] || die "Private key exists but ${key_path}.pub is missing."
  chmod 600 "${key_path}"
  chmod 644 "${key_path}.pub"
fi

if [[ ! -f "${known_hosts_path}" ]] || ! ssh-keygen -F github.com -f "${known_hosts_path}" >/dev/null 2>&1; then
  temporary_known_hosts="$(mktemp "${ssh_root}/known_hosts.XXXXXX")"
  trap 'rm -f "${temporary_known_hosts}"' EXIT
  gh api meta --jq '.ssh_keys[]' | sed 's/^/github.com /' >"${temporary_known_hosts}" \
    || die "Could not retrieve GitHub host keys from the GitHub API."
  [[ -s "${temporary_known_hosts}" ]] || die "GitHub host-key lookup returned no keys."
  chmod 644 "${temporary_known_hosts}"
  mv "${temporary_known_hosts}" "${known_hosts_path}"
  trap - EXIT
fi

key_title="opencode-workspace-manager-$(hostname -s 2>/dev/null || hostname)"
public_key="$(<"${key_path}.pub")"
registered_keys="$(gh api user/keys --paginate --jq '.[].key')" \
  || die "Could not list your GitHub SSH keys. Refresh gh auth with admin:public_key, then rerun."
if ! grep -Fqx "${public_key}" <<<"${registered_keys}"; then
  printf 'Registering the public key on GitHub account %s...\n' "${github_login}"
  if ! gh ssh-key add "${key_path}.pub" --title "${key_title}" >/dev/null; then
    die "Could not register the public key. Refresh gh auth with admin:public_key, or add ${key_path}.pub manually in GitHub Settings > SSH and GPG keys."
  fi
else
  printf 'The dedicated public key is already registered on GitHub account %s.\n' "${github_login}"
fi

cat >"${env_path}" <<EOF
# Generated by scripts/setup-github-ssh.sh. Do not commit.
OPENCODE_SSH_KEY_PATH=${key_path}
OPENCODE_KNOWN_HOSTS_PATH=${known_hosts_path}
EOF
chmod 600 "${env_path}"

printf 'Testing SSH authentication as %s...\n' "${github_login}"
ssh_output="$(ssh \
  -i "${key_path}" \
  -o BatchMode=yes \
  -o IdentitiesOnly=yes \
  -o StrictHostKeyChecking=yes \
  -o UserKnownHostsFile="${known_hosts_path}" \
  -T git@github.com 2>&1 || true)"
if [[ "${ssh_output}" != *"successfully authenticated"* ]]; then
  printf '%s\n' "${ssh_output}" >&2
  die "GitHub SSH authentication failed. Check the registered key and repository access."
fi

printf '%s\n' \
  "GitHub SSH authentication succeeded for ${github_login}." \
  "Compose env written to ${env_path}." \
  'Start the app with:' \
  "  docker compose --env-file .env --env-file ${env_path} -f docker-compose.local.yml -f docker-compose.ssh.yml up -d --build"
